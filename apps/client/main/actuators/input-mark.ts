/**
 * РЕЕСТР СОБСТВЕННОГО ВВОДА ДЖАРВИСА — один на весь клиент.
 *
 * 🔴 Зачем отдельный модуль (адверс-ревью 2026-09-02, HIGH): системный простой (`powerMonitor
 * .getSystemIdleTime`) сбрасывает ЛЮБОЙ ввод, включая наш собственный SendInput. Поэтому и гейт
 * «не мешать владельцу», и строка присутствия в снимке ПК обязаны вычитать наш ввод — а отметка
 * ставилась ВРУЧНУЮ в `actuators/index.ts`, то есть ровно на путях, которые через этот switch
 * проходят. Мимо реестра шли: быстрый реплей навыка (skill-runner дёргает input.* напрямую),
 * медиа-клавиши `system.media` (keybd_event через PowerShell) и tier0-громкость (SendKeys). Итог:
 * во время 80-секундного реплея снимок две минуты подряд утверждал «Пользователь: за ПК», хотя
 * владельца не было в комнате, а `userActiveNow()` мог зарубить наш же проактивный реплей как
 * USER_BUSY.
 *
 * Отметка ставится ТАМ, ГДЕ ВВОД РЕАЛЬНО ИНЖЕКТИТСЯ (input.ts / system.ts / tier0), — тогда любой
 * будущий вызывающий помечается сам, без правки списка call-site'ов.
 */

let lastAt = 0;

/** Пометить: ввод только что инжектили МЫ (Date.now-мс). */
export function noteJarvisInput(): void {
  lastAt = Date.now();
}

/** Когда Джарвис последний раз сам инжектил ввод; 0 — никогда за эту сессию процесса. */
export function lastJarvisInput(): number {
  return lastAt;
}

/**
 * ГРАУНД-ТРУС присутствия владельца: сайдкар отличает НАШУ синтетику от живого ввода по
 * `dwExtraInfo` (InputSynthesizer.SyntheticMarker) и шлёт push «user-input». Этот сигнал не обмануть
 * нашими же кликами — в отличие от глобального `powerMonitor.getSystemIdleTime()`, который сбрасывает
 * любой ввод. Пока сайдкар жив, присутствие считается по нему; idle-эвристика остаётся фолбэком.
 */
let lastUserAt = 0;

/** Сайдкар подтвердил ЖИВОЙ ввод владельца (не нашу синтетику). */
export function noteOwnerInput(): void {
  lastUserAt = Date.now();
}

/** Когда владелец последний раз вводил ПО ДАННЫМ САЙДКАРА; 0 — сигнала не было. */
export function lastOwnerInput(): number {
  return lastUserAt;
}

/** Только для тестов: забыть отметку. */
export function _resetJarvisInputForTest(): void {
  lastAt = 0;
  lastUserAt = 0;
}

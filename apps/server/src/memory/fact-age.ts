/**
 * ВОЗРАСТ ФАКТА в доверенном блоке промпта (волна H, шаг 1 — 2026-08-31).
 *
 * Корень (найден ресёрчем подходов к памяти и подтверждён по коду): «Известные факты» — голый список
 * строк БЕЗ времени. Когда в нём оказываются два противоречащих факта («работает в Сбере» и
 * «работает в Яндексе» — косинус ~0.86, ниже дедуп-порога 0.93, поэтому оба записались), модель
 * выбирает между ними НАУГАД и уверенно называет устаревшее — в блоке, который промпт объявляет
 * достоверным. Это действующее нарушение закона честности, а не гипотеза.
 *
 * Почему именно дата, а не «пусть модель разберётся»: отслеживание свежести — ровно то, что LLM
 * держит хуже всего (замеры в ресёрче: деградация ~75%→61% на длинной истории). Поэтому разделение
 * труда: СЕМАНТИКУ («это про одно и то же?») решает модель, СВЕЖЕСТЬ считает код и печатает явно.
 *
 * Формат намеренно КОРОТКИЙ («с марта», «вчера»): факты живут в НЕкешируемом хвосте промпта (§15),
 * и каждый символ идёт в каждый ход. Полная дата не нужна — нужен ПОРЯДОК свежести.
 * Легаси-факты без метаданных печатаются БЕЗ пометки: выдуманная дата хуже отсутствия даты.
 */

const MONTHS_RU = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
];

/** Человеческая метка возраста: «сегодня» / «вчера» / «на прошлой неделе» / «с марта» / «с марта 2025». */
export function factAgeLabel(ts: number, now: number): string | undefined {
  if (!Number.isFinite(ts) || ts <= 0 || ts > now + 86_400_000) return undefined; // мусор/будущее — молчим
  const days = Math.floor((now - ts) / 86_400_000);
  if (days <= 0) return "сегодня";
  if (days === 1) return "вчера";
  if (days < 7) return `${days} дн. назад`;
  if (days < 21) return "на прошлой неделе";
  const d = new Date(ts);
  const nowY = new Date(now).getFullYear();
  const month = MONTHS_RU[d.getMonth()] ?? "";
  return d.getFullYear() === nowY ? `с ${month}` : `с ${month} ${d.getFullYear()}`;
}

/**
 * Разметить факты возрастом для asserted-блока. Метаданные приходят из sidecar-стора провенанса
 * (`profile.readFactMeta`, волна F): у факта без записи метка не ставится.
 * Чистая функция — вызывающий отвечает за загрузку карты и за `now`.
 */
export function withFactAges(
  facts: readonly string[],
  meta: ReadonlyMap<string, { ts?: number }>,
  now: number,
): string[] {
  return facts.map((f) => {
    const ts = meta.get(f)?.ts;
    const label = ts === undefined ? undefined : factAgeLabel(ts, now);
    return label ? `(${label}) ${f}` : f;
  });
}

// Скан контента навыка ПЕРЕД записью (§8/§sec; волна F «адаптация OpenClaw» F2, 2026-08-31).
//
// Зачем: выученный навык на recall инжектится ДОВЕРЕННЫМ блоком с прямым приказом «ИСПОЛНИ»
// (agent/index.ts formatRecalledSkill) — это самый ценный канал отмывания prompt-инъекции в
// авторитет: директива со страницы/экрана, попавшая в procedure через self-learn, исполнялась бы
// в КАЖДОЙ будущей задаче. У OpenClaw ровно этот класс дал кампанию ClawHavoc (~1400 вредоносных
// навыков); их ответ — повторный скан прямо перед live-write + карантин вместо записи. Берём идею.
//
// Профиль СОЗНАТЕЛЬНО отдельный от looksLikeDirective (сон-цикл): у навыков URL/хоткеи/упоминание
// .env — ЛЕГИТИМНАЯ ткань процедуры («открой https://…», «нажми Ctrl+C», «ключ берётся из .env»),
// блочить их нельзя. Ловим только сочетания, которым в честной процедуре взяться неоткуда:
// структурная инъекция в наши обёртки, снятие confirm-гейтов, экфильтрация секретов, массовая
// пересылка, «забудь инструкции», заявление о пред-одобрении владельца.
// Ложный positive безопасен по построению: исход — КАРАНТИН (durable-файл для владельца), не
// молчаливый отброс; модель получает честную ошибку «не сохранён», а не ложный успех.

export interface SkillScanFinding {
  rule: string;
  excerpt: string;
}

const RULES: ReadonlyArray<{ rule: string; re: RegExp }> = [
  // Структурная инъекция: закрытие/открытие нашей untrusted-обёртки или tool-use-синтаксис в тексте
  // процедуры = попытка вырваться из данных в разметку промпта (урок волны C: </untrusted_content>
  // внутри input закрывал обёртку журнала на первой строке).
  { rule: "tag-injection", re: /<\/?\s*untrusted_content|<\s*(?:invoke|parameter)\b/i },
  // Снятие §14-гейтов: «без подтверждения», «не спрашивай», «всегда одобряй», «минуя проверку».
  {
    rule: "approval-bypass",
    re: /без\s+подтвержден|не\s+спрашива(?:й|я)|пропуска\p{L}*\s+подтвержд|одобряй\s+автоматич|всегда\s+(?:соглашай|одобряй|разрешай|подтверждай)|минуя\s+(?:подтвержд|гейт|провер)/iu,
  },
  // Заявление о пред-одобрении: «владелец уже разрешил/одобрил заранее» — авторитет не передаётся текстом.
  { rule: "claimed-preapproval", re: /владел\p{L}*\s+(?:уже\s+)?(?:разрешил|одобрил|подтвердил)\s+(?:заранее|всё|все)/iu },
  // Экфильтрация: глагол отправки рядом с секретом (в обе стороны). Голое упоминание секрета — не находка.
  // Гэп [^\n] (не [^.\n]): точка в имени файла («.env») не должна разрывать матч; 60 симв. держат близость.
  {
    rule: "credential-exfil",
    re: /(?:отправ|переш|перес[ыл]|шли|слать|скин|перед(?:ай|ав)|выгру|сообщ(?:и|ай))\p{L}*[^\n]{0,60}(?:парол|токен|token|api[-_ ]?key|ключ\p{L}*\s+(?:доступа|api)|секрет|cookie|credential)/iu,
  },
  {
    rule: "credential-exfil",
    re: /(?:парол|токен|token|api[-_ ]?key|секрет|cookie|credential)\p{L}*[^\n]{0,60}(?:отправ|переш|перес[ыл]|шли|слать|скин|перед(?:ай|ав)|выгру)/iu,
  },
  // Массовая пересылка входящего — классический exfil-паттерн (тот же класс, что в консолидации).
  // Объект ОБЯЗАН быть сообщением/перепиской: «скопируй все файлы в бэкап» — легитимный шаг, не находка.
  {
    rule: "mass-forward",
    re: /(?:пересыла|перенаправля|forward|дублируй|копируй)\p{L}*[^.\n]{0,40}(?:входящ|сообщени|письм|переписк|уведомлени|почт)/iu,
  },
  // «Забудь/игнорируй инструкции» — прямой jailbreak-стем (рус + англ).
  {
    rule: "ignore-instructions",
    re: /(?:игнорируй|забудь|отбрось|отмени)\p{L}*[^.\n]{0,40}(?:инструкци|правил|персон|систем|ограничен|запрет)|ignore\s+(?:all\s+)?(?:previous|prior)\s+instructions|new\s+system\s+prompt/iu,
  },
];

const EXCERPT_PAD = 24;

/** Скан сырого текста (procedure/when/name или content_md целиком). Пусто = чисто. */
export function scanSkillText(text: string): SkillScanFinding[] {
  const t = String(text ?? "");
  const out: SkillScanFinding[] = [];
  for (const { rule, re } of RULES) {
    const m = re.exec(t);
    if (!m) continue;
    const from = Math.max(0, m.index - EXCERPT_PAD);
    const excerpt = t.slice(from, m.index + m[0].length + EXCERPT_PAD).replace(/\s+/g, " ").trim();
    if (!out.some((f) => f.rule === rule)) out.push({ rule, excerpt: excerpt.slice(0, 120) });
  }
  return out;
}

/** Скан входа skill_save: имя + when + процедура (имя тоже инжектится — в каталог навыков). */
export function scanSkillContent(input: { name: string; when: string; procedure: string }): SkillScanFinding[] {
  return scanSkillText(`${input.name}\n${input.when}\n${input.procedure}`);
}

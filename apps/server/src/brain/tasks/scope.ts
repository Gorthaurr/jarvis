/**
 * Классификатор «правка текущей задачи vs новая отдельная задача» (§20, параллельность).
 *
 * Применяется ТОЛЬКО когда уже выполняется фоновая задача и пришла НОВАЯ содержательная
 * реплика (не команда управления — это отдельный classifyTaskControl). Цель — различить:
 *  - «edit»: реплика правит/дополняет то, что Джарвис сейчас делает («добавь раздел»,
 *    «сделай подробнее», «убери последнее») → продолжаем в контексте текущей задачи;
 *  - «new»: это ОТДЕЛЬНОЕ дело («а ещё закажи такси», «открой почту») → запускаем новую
 *    параллельную задачу со СВОИМ чистым контекстом, чтобы она не путалась с текущей.
 *
 * Корень жалобы: сейчас новая реплика во время задачи всегда тянет контекст текущей → «вторую
 * обособленную задачу не дать». Поэтому по умолчанию (без явных правочных маркеров) → «new».
 * Чистая детерминированная функция (как classifyTaskControl) — без LLM/сети/состояния.
 */

import { foldText, latinToCyrillic } from "@jarvis/shared";

/** Решение о области реплики относительно активной задачи. */
export type TaskScope = "edit" | "new";

/** Нормализация для матча по словам (единый `foldText` из @jarvis/shared, окаймление пробелами). */
const normalize = (text: string): string => foldText(text, { pad: true });

/**
 * Явные маркеры ПРАВКИ текущего результата (модификация того, что уже делается). Консервативно:
 * только слова, которые трудно спутать с самостоятельным делом. Неоднозначные («ещё», «также»)
 * НЕ включаем — они часто значат «вдобавок ОТДЕЛЬНО».
 */
const EDIT_STEMS = [
  "добавь", "добавить", "допиши", "дополни", "дополнить", "расширь", "расширить",
  "сократи", "укороти", "удлини", "измени", "изменить", "исправь", "исправить",
  "поправь", "поправить", "переделай", "переделать", "замени", "заменить",
  // «короче» убрано — это массовый филлер («короче, закажи такси» — это НОВАЯ задача, не правка).
  "переименуй", "детальн", "подробн", "длинн", "побольше", "поменьше",
] as const;

/**
 * Маркеры-ссылки на ТЕКУЩИЙ объект. Голые «в этом/в эту/в этот» убраны — это частотные
 * обстоятельства («в этом городе найди отель» — новая задача), давали ложный edit. Оставлены
 * формы, явно указывающие на объект правки.
 */
const EDIT_REFERENCES = [
  "туда", "сюда", "там же", "в тот же", "в ту же",
  "к нему", "к ней", "к этому", "в него", "в нее", "его подробнее", "это подробнее",
  // Специфичные формы «в этот <объект>» — это правка текущего артефакта (НЕ голое «в этом году»).
  "в этот документ", "в эту таблицу", "в этот файл", "в этот текст", "в это письмо",
  "в этот список", "в этот отчет", "в этот реферат", "в эту презентацию",
] as const;

/**
 * Маркеры ОТКАЗА/РЕДИРЕКТА текущего хода («делаешь не то, переиграй») — сильный сигнал ПРАВКИ во время
 * задачи. Применяется только при активной задаче, поэтому «не то/не так» тут почти наверняка = «не туда
 * пошёл», а не самостоятельное дело. Бареное «нет/иначе/лучше» НЕ включаем — слишком частотны вне правки.
 */
const REJECT_MARKERS = [
  "не то", "не так", "не это", "не туда", "не такой", "не такую", "не такое",
  "не правильно", "неправильно", "вместо", "по другому", "не нужно так",
  // A2 (форензика 2026-07-14): ПРЕТЕНЗИЯ «не сработало/не сделано» при активной задаче — это правка
  // текущего (re-verify/добей), а НЕ новая задача. Раньше «это не сделал», «нихуя не перемотал», «не
  // ушло» уходили scope=new → вторая пустая петля вместо доведения. КОНКРЕТНЫЕ «не + сделанное»
  // (ревью р2 #4: общие «ничего не»/«так и не»/«до сих пор не» УБРАНЫ — «на завтра ничего не
  // запланировано» проглатывалось как правка чужой задачи).
  "не сделал", "не сделала", "не сделано", "не ушло", "не ушла", "не отправил", "не отправила",
  "не отправлено", "не перемотал", "не перемотала", "не ввёл", "не ввел", "не нажал", "не открыл",
  "не запустил", "не получилось", "не сработало", "не сработал", "нихуя не", "ни хуя не",
] as const;

function hasStem(norm: string, stems: readonly string[]): boolean {
  return stems.some((s) => norm.includes(` ${s}`));
}
// norm окаймлён пробелами → ` фраза ` матчит по границам слов (не подстрокой внутри слова).
function hasPhrase(norm: string, phrases: readonly string[]): boolean {
  return phrases.some((p) => norm.includes(` ${p} `));
}

/**
 * ПРЕТЕНЗИЯ/СТАТУС-ЗАПРОС о ходе активной задачи («ты не сделал», «я не вижу, чтобы ты что-то делал»,
 * «что там», «сделал?», «готово?», «долго ещё») — это НЕ инструкция-правка (добавь/переделай/вместо),
 * а нетерпение или вопрос о ходе. Для задачи-ОЖИДАНИЯ (watch) steer — no-op, и «Принял, поправляю»
 * вводит в заблуждение (правит нечего). Такую реплику надо встречать ЧЕСТНЫМ статусом, а не «поправляю».
 * Претензионный подсет REJECT_MARKERS («не сделал/не сработало/не перемотал» — жалоба на невыполнение)
 * СЮДА входит, а РЕДИРЕКТ («не то/не так/вместо/по другому» — реальная правка курса) — НЕТ.
 */
const COMPLAINT_MARKERS = [
  "не сделал", "не сделала", "не сделано", "не ушло", "не ушла", "не отправил", "не отправила",
  "не отправлено", "не перемотал", "не перемотала", "не ввёл", "не ввел", "не нажал", "не открыл",
  "не запустил", "не получилось", "не сработало", "не сработал", "нихуя не", "ни хуя не",
] as const;
const STATUS_QUERY_MARKERS = [
  "не вижу", "ничего не происходит", "что там", "как там", "ну что", "ну как", "что по",
  "готово", "сделал", "сделала", "закончил", "закончила", "успел", "успела", "долго",
  "ты там", "работаешь", "делаешь", "происходит",
] as const;

/**
 * Похоже на претензию/статус-запрос об активной задаче (нетерпение/вопрос о ходе), а НЕ на инструкцию-
 * правку. Чистая функция — используется агентом, чтобы ответить статусом вместо ложного «поправляю».
 */
export function looksLikeStatusQuery(text: string): boolean {
  const norm = normalize(text);
  if (norm === "") return false;
  return hasPhrase(norm, COMPLAINT_MARKERS) || hasPhrase(norm, STATUS_QUERY_MARKERS) || hasStem(norm, STATUS_QUERY_MARKERS);
}

// ── Пост-терминальный гейт (эпизод «двойная отправка» 2026-07-24) ────────────────────────────────
// Гонка голосового UX: пользователь договаривает мысль, пока задача летит; обрывок («Это написал.»)
// эндпоинтится через СЕКУНДУ ПОСЛЕ терминала задачи → активной задачи уже нет, все гейты §20 слепы,
// рождается ВТОРАЯ петля, и модель повторяет действие (второе сообщение Кате). Ниже — предикаты для
// перехвата таких обрывков сразу после завершения задачи (агент отвечает честным статусом, не петлёй).

/**
 * Глагольные заявки-подтверждения «сделано» (прошедшее время/статус) — то, что пользователь говорит
 * О только что сделанном, а не приказывает сделать. Императивы («напиши», «отправь») сюда НЕ входят.
 */
const DONE_ECHO_CLAIMS = [
  "написал", "написала", "написано", "отправил", "отправила", "отправлено", "сделал", "сделала",
  "сделано", "готово", "получилось", "ушло", "закончил", "закончила", "успел", "успела",
  "запустил", "запустила", "открыл", "открыла", "включил", "включила", "поставил", "поставила",
] as const;
/**
 * Служебные слова, допустимые РЯДОМ с заявкой (дейксис/частицы/вежливость). ⚠️ Позитивный allowlist
 * принципиально (см. §econ isPureSocial): любой СОДЕРЖАТЕЛЬНЫЙ токен вне списка («брату», «кате»)
 * выбивает реплику из гейта — ей займётся модель с полным контекстом. «не» намеренно ИСКЛЮЧЕНО:
 * «не написал» — претензия, ей положена перепроверка петлёй, а не плоское «да, отправил».
 */
const DONE_ECHO_FILLERS = new Set([
  "это", "ты", "все", "всё", "уже", "точно", "правда", "реально", "ну", "а", "и", "же", "ли",
  "да", "вот", "так", "что", "там", "сэр", "джарвис", "спасибо", "ладно", "хорошо", "окей", "ок",
]);
const DONE_ECHO_MAX_TOKENS = 4;

/**
 * Короткое эхо-подтверждение/статус СРАЗУ после завершения задачи («Это написал.», «готово?»,
 * «ты отправил») — не новая команда. Все токены ∈ (заявки ∪ служебные), есть хотя бы одна заявка,
 * длина ≤4 токенов. Чистая функция; применяется ТОЛЬКО в коротком окне после терминала (агент).
 */
export function looksLikeDoneEcho(text: string): boolean {
  const tokens = normalize(text).split(/\s+/u).filter(Boolean);
  if (tokens.length === 0 || tokens.length > DONE_ECHO_MAX_TOKENS) return false;
  const claims = new Set<string>(DONE_ECHO_CLAIMS);
  let hasClaim = false;
  for (const t of tokens) {
    if (claims.has(t)) hasClaim = true;
    else if (!DONE_ECHO_FILLERS.has(t)) return false; // содержательный токен → решает модель
  }
  return hasClaim;
}

// ⚠️ Дубль-гейт ПО ЦЕЛИ после терминала («повтор» → «Уже отправил») здесь сознательно ОТСУТСТВУЕТ
// (контрольное ревью 2026-07-24, 2 HIGH): лексика не отличает повтор от ПОПРАВКИ («…что я НЕ приду»)
// или ДРУГОГО адресата («…маме») — молчаливый перехват глотал реальный приказ с ложным «Уже отправил».
// Защита от дубля живёт на messaging-слое (ресенд-гард: identical → «повтор не ушёл», similar → confirm).

// ── Связь реплики с ОБЪЕКТОМ активной задачи (фикс ложного «Принял, поправляю», 2026-09-01) ──────
// Живой дефект (доказан прогоном): при активной задаче ЛЮБАЯ реплика с глаголом правки уезжала
// steer'ом в ЧУЖУЮ задачу, а владельцу произносили «Принял, поправляю» о том, чего не произошло:
//   «добавь напоминание позвонить маме завтра» / «исправь баг в билде» / «измени раскладку
//   клавиатуры» — все три давали edit при активной задаче «напиши отчёт про рынок».
// Правку от смены темы решает СВЯЗЬ С ОБЪЕКТОМ, а не наличие глагола: реплика либо вовсе не несёт
// своего объекта (чистый модификатор «сделай подробнее»), либо её объект — часть производимого
// артефакта («раздел», «вступление»), либо он пересекается с целью активной задачи.
//
// ⚠️ Семантический бэкстоп e5 здесь СОЗНАТЕЛЬНО НЕ СТАВИТСЯ — ЗАМЕРЕНО живьём на боевом эмбеддере
// (multilingual-e5-small, dml/fp32, 2026-09-01): «добавь раздел про флот» ↔ «напиши отчёт про рынок
// электромобилей» = 0.836 и РОВНО 0.836 ↔ «запусти поиск матча в доте»; «измени раскладку
// клавиатуры» ↔ отчёт = 0.818, «добавь график продаж» ↔ отчёт = 0.846. Весь диапазон 0.77–0.85 —
// шум, разделяющего порога НЕ существует (тот же документированный предел e5-small, что в recall
// навыков). Порог дубль-гейта (0.86) не дал бы edit НИ ОДНОЙ настоящей правке → слой был бы
// декоративным, а порог ниже — вернул бы ровно тот дефект, который чиним.

/**
 * Служебные слова, не несущие СВОЕГО объекта: дейксис, частицы, вежливость, обращения и голые
 * общие глаголы («сделай»). Нужны, чтобы отличить чистый модификатор («сделай подробнее») от
 * реплики с собственным делом («добавь напоминание позвонить маме»).
 */
const SCOPE_FILLERS = new Set([
  "это", "то", "так", "там", "тут", "здесь", "тогда", "теперь", "уже", "ещё", "еще", "же", "ли",
  "а", "и", "но", "да", "нет", "ну", "вот", "блин", "пожалуйста", "давай", "давайте", "сэр",
  "джарвис", "ты", "мне", "нам", "его", "ее", "их", "все", "всё", "чуть", "немного", "лучше",
  "сделай", "сделайте", "сделать", "делай", "надо", "нужно", "просто", "быстро", "получше",
]);

/**
 * Части ПРОИЗВОДИМОГО артефакта — объект, который сам по себе НЕ является отдельным делом
 * («раздел», «вступление», «строка»). Матч ПРЕФИКСОМ по сырому токену (словоформы).
 *
 * ⚠️ Позитивный allowlist ПРИНЦИПИАЛЬНО (как `isPureSocial`/`DONE_ECHO_FILLERS`): его неполнота
 * ошибается в БЕЗОПАСНУЮ сторону — незнакомое слово даёт «new» (честная отдельная задача), а не
 * ложное «Принял, поправляю» о работе, которой не было. Целые артефакты («отчёт», «презентация»,
 * «таблица») сюда НЕ входят: они бывают самостоятельным делом («сделай презентацию по проекту»).
 */
const ARTIFACT_PARTS = [
  "раздел", "подраздел", "пункт", "подпункт", "абзац", "глав", "строк", "столб", "колонк",
  "заголов", "подзаголов", "вступлен", "введен", "заключен", "вывод", "оглавлен", "сноск",
  "цитат", "фрагмент", "формулировк", "примечан", "эпиграф", "пример", "подробност", "детал",
  "часть", "части", "текст", "перечислен",
] as const;

/** Токен относится к части текущего артефакта (словоформа по префиксу). */
function isArtifactPart(token: string): boolean {
  return ARTIFACT_PARTS.some((p) => token.startsWith(p));
}

/** Токен — правочный глагол/модификатор (тот же префиксный матч, что и в `hasStem`). */
function isEditWord(token: string): boolean {
  return EDIT_STEMS.some((s) => token.startsWith(s));
}

/**
 * Короткие СЛУЖЕБНЫЕ слова (предлоги, союзы, частицы, местоимения) — они не несут объекта.
 *
 * 🔴 Раньше вместо списка стояла отсечка длины (`t.length >= 4`), и она выбрасывала заодно КОРОТКИЕ
 * ОБЪЕКТЫ: «баг», «код», «тон», «лог», «чат», «имя», «фон». При идущей фоновой задаче реплика
 * «исправь баг» снова считалась правкой ТОЙ задачи — владелец слышал «Принял, поправляю» о работе,
 * которой не было, а его инструкция впрыскивалась в чужую петлю (ровно тот дефект, ради которого
 * гейт и вводился, просто уцелевший на словах короче четырёх букв).
 *
 * Список неполон СОЗНАТЕЛЬНО и ошибается в безопасную сторону: незнакомое короткое слово остаётся
 * значимым токеном → «new» (честная отдельная задача), а не ложная правка.
 */
const SHORT_FUNCTION_WORDS = new Set([
  "во", "до", "за", "из", "ко", "на", "над", "об", "от", "по", "под", "при", "про", "со", "для",
  "без", "не", "ни", "ну", "же", "ли", "бы", "то", "уж", "аж", "да", "вот", "он", "она", "оно",
  "мы", "вы", "они", "мой", "моя", "мое", "наш", "ему", "ей", "им", "их", "нам", "вам", "них",
  "нем", "тот", "та", "те", "эти", "эта", "этот", "эту", "том", "чем", "что", "как", "кто", "где",
  "тех", "там", "тут", "уже", "ага", "уж", "или", "чтоб",
]);

/**
 * Значимые токены реплики — её СОБСТВЕННЫЙ объект: без правочных глаголов, служебных слов и
 * коротких предлогов/частиц. Пусто → реплика объекта не несёт (чистый модификатор).
 */
function objectTokens(text: string): string[] {
  return normalize(text)
    .split(/\s+/u)
    .filter((t) => t.length >= 2 && !SHORT_FUNCTION_WORDS.has(t) && !SCOPE_FILLERS.has(t) && !isEditWord(t));
}

/**
 * Связана ли реплика-с-глаголом-правки с ОБЪЕКТОМ активной задачи. Подход дубль-гейта
 * (`isDuplicateGoal`) переиспользован: сравнение идёт по тем же грубым стемам (`stemToken`), чтобы
 * словоформы («отчёт» ↔ «отчёте») совпадали. Достаточно ОДНОГО связанного токена: у настоящей
 * правки объект часто шире цели («добавь раздел про флот» — «флот» цели нет, но «раздел» — часть
 * артефакта). Чистая функция.
 */
function relatedToActiveGoal(text: string, activeGoal: string): boolean {
  const obj = objectTokens(text);
  if (obj.length === 0) return true; // «сделай подробнее», «переделай» — модификатор текущей работы
  const goal = new Set(objectTokens(activeGoal).map(stemToken));
  return obj.some((t) => isArtifactPart(t) || goal.has(stemToken(t)));
}

/**
 * Классифицировать область реплики относительно активной задачи (§20). Чистая функция.
 *
 * `activeGoal` — цель ТОЙ задачи, в которую полетит steer (обязателен: без неё «edit» нечем
 * обосновать, а ложный edit = произнесённое «Принял, поправляю» о непроисшедшем).
 */
export function classifyTaskScope(text: string, activeGoal: string): TaskScope {
  const norm = normalize(text);
  if (norm === "") return "new";
  // «не то / не так / вместо / не сработало» — рулёжка ТЕКУЩИМ ходом: связь с объектом уже в самой
  // форме (претензия адресована тому, что Джарвис делает прямо сейчас).
  if (hasPhrase(norm, REJECT_MARKERS)) return "edit";
  // Явная ссылка на текущий объект («туда», «в этот документ») — это и есть связь с объектом.
  if (hasPhrase(norm, EDIT_REFERENCES)) return "edit";
  // Глагол правки САМ ПО СЕБЕ ничего не доказывает — нужна связь с объектом активной задачи.
  if (hasStem(norm, EDIT_STEMS) && relatedToActiveGoal(text, activeGoal)) return "edit";
  return "new";
}

// ── Дубль-гейт (§20, аудит 2026-07-02; усилен по эпизоду 2026-07-10) ────────────────────────────
// Живой случай 1: «продолжи видео на ютубе» и через 6 секунд «продолжу видео на ютубе» (STT-вариация /
// нетерпеливый повтор) породили ДВЕ параллельные задачи — обе пришлось отменять, «остановил» ×2.
// Живой случай 2 (2026-07-10): повтор «запусти поиск в доте» распознан ОБРЫВКОМ ЛАТИНИЦЕЙ «в dot'е.» —
// Жаккар 0.17 → вторая петля, обе убиты потолком, $1.09 впустую. Жаккар МАТЕМАТИЧЕСКИ не ловит
// фрагмент-подмножество (даже идеальное «в доте» даёт 2/4=0.5) → добавлен overlap coefficient
// (пересечение/короткая сторона) + канонизация латиницы (dot'е→доте) через latinToCyrillic.

/** Грубый стем для сравнения словоформ: у слов ≥5 букв срезаем окончание до общего корня. */
function stemToken(t: string): string {
  return t.length >= 5 ? t.slice(0, Math.max(4, t.length - 2)) : t;
}

/**
 * ПОЛНЫЕ токены фразы (без стемминга): апострофы убираем ДО foldText (иначе «dot'е» разорвётся на
 * «dot»+«е»), латиницу токена канонизируем в кириллицу primary-рендерингом (dot'е→доте) + ё→е
 * (foldText уже свернул ё исходника, а транслит мог вернуть «ё» диграфом yo).
 */
function tokenSet(text: string): Set<string> {
  return new Set(
    normalize(String(text ?? "").replace(/['’ʼ`]/gu, ""))
      .split(/\s+/u)
      .filter(Boolean)
      .map((t) => (/[a-z]/i.test(t) ? latinToCyrillic(t).replace(/ё/g, "е") : t)),
  );
}

/**
 * Почти та же ли фраза, что цель активной задачи (повтор / STT-вариация / STT-обрывок повтора)?
 * Два теста (любой достаточен), оба при ≥2 токенах с каждой стороны:
 *  • стем-Жаккар ≥ 0.75 (ТОЧНОЕ равенство стемов) — почти дословный повтор со словоформами
 *    («продолжи/продолжу видео на ютубе»: стемы обоих = «продол»);
 *  • фрагмент-overlap по ПОЛНЫМ токенам (пересечение/короткая сторона ≥ 0.8) + минимум один
 *    совпавший СОДЕРЖАТЕЛЬНЫЙ токен (≥4 букв) — фрагмент-повтор («в доте» ⊂ «запусти поиск в доте»).
 *    Именно полные токены, не стемы и не префиксы: адверсариал-ревью 2026-07-10 показало, что
 *    стем/префикс-вложение в короткой стороне даёт массовые ложные дубли («включи свет» ≈ «включи
 *    светлую тему», «проверь почту» ≈ «…он почти готов» — стемы «почт» совпадают, полные токены НЕТ).
 * Чистая функция (юнит-тест).
 */
export function isDuplicateGoal(text: string, activeGoal: string): boolean {
  const a = tokenSet(text);
  const b = tokenSet(activeGoal);
  if (a.size < 2 || b.size < 2) return false; // однословные — слишком фуззи, не рискуем

  // 1) Почти дословный повтор: Жаккар по СТЕМАМ (точное равенство — ловит словоформы продолжи/продолжу).
  const stemsA = new Set([...a].map(stemToken));
  const stemsB = new Set([...b].map(stemToken));
  let stemInter = 0;
  for (const s of stemsA) if (stemsB.has(s)) stemInter += 1;
  const union = new Set([...stemsA, ...stemsB]).size;
  if (union > 0 && stemInter / union >= 0.75) return true;

  // 2) Фрагмент-повтор: overlap по ПОЛНЫМ токенам + хотя бы одно содержательное совпадение.
  let inter = 0;
  let contentHit = false;
  for (const t of a) {
    if (b.has(t)) {
      inter += 1;
      if (t.length >= 4) contentHit = true;
    }
  }
  return contentHit && inter / Math.min(a.size, b.size) >= 0.8;
}

/** Узкая развилка: откат выполненной правки файла не равен остановке текущей задачи. */
export function isFileUndoRequest(normalized: string): boolean {
  const text = normalized.trim();
  return /^(?:(?:джарвис|jarvis|пожалуйста) )*(?:отмени|отменить|отмена|откати) (?:последн(?:юю|ее|ие|ей|его|их) )?(?:правк(?:у|и)|изменени(?:е|я|й)|редактирование) (?:в )?файл(?:а|е|ов)?(?: |$)/u.test(text);
}

/**
 * Контроль-6 (V5-6): в тексте провала реплея/берста номер шага называется ОДИН раз — клиентский префикс/хвост срезается
 * во ВСЕХ формах, которые реально шлёт skill-runner (двоеточие, «не подтвердил expect» без двоеточия, хвост «(шаг N…)»).
 */
import { describe, expect, it } from "vitest";
import { stripStepPrefix } from "./skills.js";

describe("stripStepPrefix", () => {
  it.each([
    ["шаг 3 (input.click): элемент не найден", "элемент не найден"],
    ["шаг 2 (input.key) не подтвердил expect", "не подтвердил expect"],
    ["реплей не уложился в бюджет времени (шаг 2)", "реплей не уложился в бюджет времени"],
    // Контроль-7 (sensors-7): суть скобки остаётся, срезается только номер шага.
    ["реплей не уложился в бюджет времени (шаг 2, сверка постусловия не выполнялась)", "реплей не уложился в бюджет времени (сверка постусловия не выполнялась)"],
    ["шаг 3 (input.type) требует LLM, но заполнение недоступно", "требует LLM, но заполнение недоступно"],
    ["сайдкар не ответил", "сайдкар не ответил"],
  ])("%s → %s", (input, out) => {
    expect(stripStepPrefix(input)).toBe(out);
  });
});

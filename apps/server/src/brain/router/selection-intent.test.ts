/**
 * §РЕЖИМ ВЫДЕЛЕНИЯ — tier0-команды «выдели область» / «убери выделение» ($0, без LLM).
 *
 * Матчер УЗКИЙ намеренно: «выдели текст», «выдели все ячейки», «выдели время на это» — легитимные
 * задачи для модели, и перехват их сломал бы обычную работу. Урок lean-smalltalk: денилист слов
 * принципиально неполон, поэтому здесь позитивный allowlist форм с якорями ^…$ и ПРОСТРАНСТВЕННЫМ
 * объектом. Негативные кейсы тут важнее позитивных — они охраняют чужую работу.
 */
import { describe, expect, it } from "vitest";
import { classifyTier, matchSelectionIntent } from "./index.js";

describe("matchSelectionIntent — позитив", () => {
  for (const phrase of [
    "режим выделения",
    "включи режим выделения",
    "выдели область",
    "выдели область экрана",
    "обведи участок",
    "дай я обведу",
    "хочу показать область экрана",
    "включи выделение",
  ]) {
    it(`«${phrase}» → старт режима`, () => {
      expect(matchSelectionIntent(phrase)).toEqual({ kind: "selection", op: "start" });
    });
  }

  for (const phrase of ["убери выделение", "сними выделение", "отмени выделение", "выключи режим выделения", "убери рамку"]) {
    it(`«${phrase}» → снять`, () => {
      expect(matchSelectionIntent(phrase)).toEqual({ kind: "selection", op: "clear" });
    });
  }
});

describe("matchSelectionIntent — негатив (чужую работу не забираем)", () => {
  for (const phrase of [
    "выдели текст в документе",
    "выдели все ячейки",
    "выдели время на это",
    "выдели ему бюджет",
    "отмени напоминание про таблетки",
    "сними защиту с листа",
    "выдели область в фотошопе и залей цветом",
    "покажи область на карте",
    "выделение", // голое слово (STT-обрывок/диктовка) не должно открывать вуаль, ловящую мышь
    "выделения",
  ]) {
    it(`«${phrase}» — НЕ команда режима выделения`, () => {
      expect(matchSelectionIntent(phrase)).toBeUndefined();
    });
  }
});

describe("проводка в classifyTier", () => {
  it("голосом с обращением и вежливостью — всё равно tier0, без LLM", () => {
    const d = classifyTier("Джарвис, выдели область экрана, пожалуйста");
    expect(d.tier).toBe("tier0");
    expect(d.local).toEqual({ kind: "selection", op: "start" });
  });

  it("«включи выделение» не уходит в запуск приложения «выделение»", () => {
    expect(classifyTier("включи выделение").local).toEqual({ kind: "selection", op: "start" });
  });
});

/**
 * 27.09 (живой лог ЭИОС): инфинитив-просьба «надо пройти / нужно сдать / помоги решить / выполнить к утру» — командный
 * глагол для hasCommandVerb (гейт подсказки навыка). ТОЧНЫЕ формы: стем «реш*» зажёгся бы на «решение/решил», «сда*» —
 * на «сдаётся мне». Не в ACTION_VERB_RE роутера: тот судит рассуждение-vs-действие (isHard) — «продумай, как решить…»
 * ушло бы в фон. Отрицание перед инфинитивом — жалоба или отказ, не приказ (адверс-ревью р1): «не могу пройти мини-тест,
 * там ошибка» иначе тянул процедуру «входи САМ» в ответ на жалобу. «Не забудь пройти» — приказ.
 */
const TASK_INFINITIVE_RE = /(?<![а-яёa-z0-9])(?:пройти|сдать|решить|выполнить)(?![а-яёa-z0-9])/giu;
// «не» (отдельным словом) и до двух слов до инфинитива: «не могу », «не надо ничего », «не успел сегодня ».
const NEGATED_TAIL_RE = /(?:^|[^а-яёa-z0-9])не(?!\s+забуд)(?:\s+\S+){0,2}\s*$/iu;

/** Есть ли в реплике НЕотрицаемый инфинитив учебной/рабочей задачи. */
export function taskInfinitive(text: string): boolean {
  for (const m of text.matchAll(TASK_INFINITIVE_RE)) {
    if (!NEGATED_TAIL_RE.test(text.slice(0, m.index))) return true;
  }
  return false;
}

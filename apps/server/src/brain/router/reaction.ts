/**
 * Короткая РЕАКЦИЯ владельца без команды (ревью 2026-09-24, T-F6).
 *
 * «нет», «не надо», «хорошо», «понял», «вообще хорошо сейчас стало», «да, не просил ничего
 * останавливать» — это РАЗГОВОР, а не задача. Раньше такая реплика падала в fallback роутера
 * «неизвестное = задача-действие» → sonnet-петля, чип задачи, «Берусь, сэр» и ответ через 5 с на
 * «нет, не надо» (живой лог 09.09); вдобавок recall навыка приносил в промпт чужую процедуру.
 *
 * ПОЗИТИВНЫЙ allowlist (блоклист команд в проекте признан принципиально неполным — урок
 * lean-smalltalk): реплика ЦЕЛИКОМ состоит из слов-реакций, и первое слово — сама реакция.
 * Единственное послабление — ИНФИНИТИВ ПОД ОТРИЦАНИЕМ («не просил ничего останавливать»):
 * отрицаемое действие командой не является. Любой командный глагол (детекторы передаёт роутер —
 * те же, что у него и у гейта реплея) → не реакция, прежний путь. Чистые функции.
 */
import { foldText } from "@jarvis/shared";

/** Вид реакции: «affirm» — согласие (может подтверждать предложенное Джарвисом действие), «other» — прочее. */
export type ReactionKind = "affirm" | "other";

/** Первое слово — сама реакция. */
const LEADS: ReadonlySet<string> = new Set([
  "да", "нет", "неа", "не", "ага", "угу", "ок", "окей", "хорошо", "ладно", "давай", "понял", "поняла",
  "поняли", "понятно", "ясно", "вообще", "ну", "отлично", "нормально", "норм", "верно", "правильно",
  "точно", "конечно", "разумеется", "пожалуй", "уже", "все", "всё", "лучше", "работает", "заработало",
  "получилось", "помогло", "спасибо", "благодарю",
]);

/** Согласие — ему отдельная судьба: после вопроса Джарвиса «да» подтверждает действие (см. agent). */
const AFFIRM: ReadonlySet<string> = new Set([
  "да", "ага", "угу", "ок", "окей", "хорошо", "ладно", "давай", "конечно", "разумеется", "точно", "верно",
]);

/** Благодарность/закрытие: «хорошо, спасибо» на «Ещё что-нибудь?» — конец разговора, а не согласие на действие. */
const CLOSURE: ReadonlySet<string> = new Set(["спасибо", "благодарю", "спс", "пасиб", "все", "пока"]);

/** Отрицания: после них инфинитив — отрицаемое действие, а не приказ. */
const NEGATIONS: ReadonlySet<string> = new Set(["не", "нет", "неа", "ничего", "никак", "ни"]);

/** Остаток реакции: частицы, местоимения, оценки, отчёт о состоянии. Всё прочее — «содержательное». */
const REST: ReadonlySet<string> = new Set([
  ...LEADS, ...NEGATIONS,
  "так", "вот", "это", "то", "сейчас", "теперь", "стало", "стал", "стала", "хуже", "надо", "нужно", "нужен",
  "просил", "просила", "говорил", "говорила", "спрашивал", "спрашивала", "имел", "виду", "тебе", "тебя",
  "ты", "я", "мне", "меня", "мы", "нам", "и", "а", "но", "же", "бы", "вроде", "пока", "прошло", "сэр",
  "джарвис", "пожалуйста", "спс", "пасиб", "совсем", "вовсе", "просто", "зря", "там", "тут", "здесь",
  "блин", "бля", "нафиг", "пофиг", "похуй", "нахуй", "молодец", "супер", "класс", "круто", "всем",
  "очень", "большое",
]);

/** Инфинитив (грубо, по окончанию): «останавливать», «делать», «идти», «беречь». */
const INFINITIVE_RE = /(?:ть|ться|ти|чь)$/u;

/** Длиннее — уже не реплика-реакция, а рассказ или задача. */
const MAX_TOKENS = 7;

/**
 * Реакция ли это; null — нет (реплика идёт прежним путём). `stripped` — уже без обращения и ведущих
 * филлеров (роутерный stripWakeAndFiller). Вопрос («?») реакцией не считается — у него своя ветка.
 */
export function classifyReaction(stripped: string, hasCommandVerb: (t: string) => boolean): ReactionKind | null {
  const raw = stripped.trim();
  if (!raw || raw.endsWith("?")) return null;
  if (hasCommandVerb(raw)) return null; // любой командный глагол → прежний путь
  const toks = foldText(raw).split(" ").filter(Boolean);
  if (toks.length === 0 || toks.length > MAX_TOKENS) return null;
  if (!LEADS.has(toks[0]!)) return null;
  let negated = false;
  for (const t of toks) {
    if (NEGATIONS.has(t)) negated = true;
    if (REST.has(t)) continue;
    if (negated && INFINITIVE_RE.test(t)) continue; // «не просил ничего останавливать»
    return null; // содержательное слово — это не реакция
  }
  return AFFIRM.has(toks[0]!) && !toks.some((t) => NEGATIONS.has(t) || CLOSURE.has(t)) ? "affirm" : "other";
}

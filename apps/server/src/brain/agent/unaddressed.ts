/**
 * Реплика БЕЗ обращения (прод 26.09, A1): окно разговора приняло звук фильма без «Джарвис» (viaWake=false) —
 * перехват эмоции записал в профиль подачу «angry» навсегда, а модель через memory_write — выдуманное «правило
 * владельца». Такая реплика может быть чужой речью (ролик, люди в комнате), поэтому ДОЛГОВРЕМЕННОЕ она не
 * меняет: профиль (имя, режим, эмоция), факты (memory_write/forget, рефлексы, сон-цикл), самообучение навыков.
 * Сброс к обычному тону/режиму — можно (безопасное направление). Судит ПОСЛЕДНЯЯ реплика владельца
 * (deps.unaddressedUtterance) — правка на ходу («Джарвис, и запомни…») адресует и начатую без обращения задачу.
 * Напоминания/наблюдения из окна НЕ гейтятся: это видимые действия (Джарвис вслух говорит, что поставил, —
 * владелец отменит), а порча памяти и профиля — тихая и навсегда.
 */
import { createLogger } from "@jarvis/shared";
import { verbalize } from "../verbalize/index.js";
import type { AgentReply } from "./types.js";
import type { TurnCtx } from "./turn-intercepts.js";

const log = createLogger("agent");

export const UNADDRESSED_MEMORY =
  "Последняя реплика пришла без обращения «Джарвис» (могла быть чужая речь — ролик, люди в комнате) — в " +
  "долговременную память НЕ записал и ничего не забыл. Скажи владельцу честно; если это его просьба — пусть " +
  "повторит с «Джарвис». Обходить это другими инструментами нельзя.";

/** Ход принят без обращения → долговременное не трогаем (с записью в лог, что именно пропустили). */
export function skipUnaddressed(meta: { viaWake?: boolean } | undefined, what: string): boolean {
  if (meta?.viaWake !== false) return false;
  log.info("реплика без обращения «Джарвис» — долговременное не меняю", { what });
  return true;
}

/** Команда настройки без обращения: не применяем и ЧЕСТНО говорим об этом (а не отдаём модели — её «как скажете»
 *  было бы ложным успехом: инструмента смены режима/имени у неё нет). */
export function refuseUnaddressed(t: TurnCtx, what: string): AgentReply | null {
  if (!skipUnaddressed(t.meta, what)) return null;
  const reply: AgentReply = { voice: verbalize("Без обращения настройки не меняю, сэр. Если это вы — скажите «Джарвис» и повторите.") };
  t.deps.memory.pushTurn("assistant", reply.voice);
  return t.finishReply(reply);
}

/**
 * НАБЛЮДЕНИЕ (watch, §долгие-задачи) — durable повторяющаяся проверка условия с проактивным уведомлением.
 *
 * Гэп, который закрывает: `set_reminder` — ОДНОРАЗОВЫЙ таймер; `auto-predictor` — recurring, но ТОЛЬКО
 * торговый и не вызывается пользователем; `proactive/triggers|scheduler` — стабы. Не было generic «следи
 * за X, проверяй каждые N, скажи КОГДА Y». Watch это даёт: модель формулирует ЧТО смотреть и УСЛОВИЕ
 * на естественном языке; сервис периодически прогоняет проверку (инъектируемый checker — LLM+web/market),
 * и при выполнении условия проговаривает результат тем же каналом проактивной речи, что напоминания.
 *
 * Концепт: НЕ хардкодим источники. Checker — общий (LLM водит web_search/web_fetch/market_quote и сам
 * добывает текущее значение). Сервис не знает, ЧТО именно отслеживается — только «проверь и скажи, met ли».
 */
import { createHash } from "node:crypto";

/** Состояние наблюдения. active — следим; fired — сработало (one-shot завершилось); cancelled — снято;
 *  suspended — приостановлено после серии провалов проверки (dead-watch, D3): не тикает, не воскресает
 *  на boot, владельцу сказано ОДИН раз. */
export type WatchStatus = "active" | "fired" | "cancelled" | "suspended";

/** Запись наблюдения (durable). Источник истины — `data/watches.json`. */
export interface Watch {
  id: string;
  /** Сессия-создатель (для доставки точному каналу; на reconnect догоняем по userId). */
  sessionId: string;
  /** Владелец — уведомление доставляется ТОЛЬКО ему (как у напоминаний, §6B/B3). */
  userId: string;
  /** ЧТО отслеживать, на естественном языке («курс биткоина», «заголовок статьи на example.com»). */
  what: string;
  /** УСЛОВИЕ уведомления, на естественном языке («упал ниже 60000», «появилось слово „продано"»). */
  condition: string;
  /**
   * §Волна3 (3.4): ЛОКАЛЬНЫЙ предикат — проверка НА КЛИЕНТЕ (словарь wait_for: окно/UIA/OCR-текст/
   * звук/GSI-пуш игры) за $0 и миллисекунды, БЕЗ LLM-чекера. «Скажи, когда матч найдётся» =
   * watch с предикатом, а задача агента завершается сразу после запуска поиска — класс «долгое
   * ожидание события» уходит из agent-петли целиком. Форма — WaitCondition из @jarvis/protocol
   * (храним как unknown: watch-слой не тянет типы протокола, валидирует клиент).
   */
  predicate?: unknown;
  /** Период проверки (мс). Клампится сервисом к [minIntervalMs, …]. */
  intervalMs: number;
  /** true — продолжать следить и после первого срабатывания (отслеживание-непрерывно, антидребезг по
   *  summary); false — one-shot (после первого met → fired, снимаем). */
  continuous: boolean;
  status: WatchStatus;
  createdAt: number;
  /** Когда последний раз проверяли (для расчёта следующего due). */
  lastCheckAt?: number;
  /** Последнее наблюдённое значение (контекст для дельты/логов/следующей проверки). */
  lastValue?: string;
  /**
   * Ревью фиксов, 2-й проход (R4), только gsi+gone: когда источник последний раз наблюдался ЖИВЫМ
   * (fresh) в рамках ЭТОГО наблюдения. Видели живым → потом stale = исчез, независимо от того, попал
   * ли редкий тик в короткое окно recentlyGone клиента (иначе интервал > окна давал «лотерею»:
   * one-shot gone-watch мог молчать навсегда). Durable — переживает рестарт сервера.
   */
  sawFreshAt?: number;
  /** Когда условие сработало (для one-shot/телеметрии). */
  firedAt?: number;
  /** Антидребезг: о чём уже уведомили (в continuous не дублируем то же самое подряд). */
  lastNotifiedSummary?: string;
  /** Сработало, но активной озвучки не было (приложение закрыто) → проговорить при следующем подключении. */
  pendingNotify?: string;
  /**
   * P0 «watch умеет ДЕЙСТВОВАТЬ» (аудит 2026-07-28): ЧТО СДЕЛАТЬ при срабатывании — поручение
   * владельца на естественном языке («напиши Кате, что доставили»). При met запускается агентская
   * петля сессии владельца (реэнтри через реестр runner'ов сервиса). Текст ДОВЕРЕННЫЙ — сформулирован
   * при СОЗДАНИИ наблюдения из речи владельца, НЕ данные наблюдаемой страницы (value из проверки в
   * реплику runner'а не попадает — анти-инъекция). Пусто → только уведомление, как раньше.
   */
  action?: string;
  /**
   * F4 (волна F, «approve recurring work once» — идея OpenClaw): отпечаток ТОЧНОЙ операции, которую
   * владелец одобрил на confirm при постановке (sha256 от what|condition|action). Перед КАЖДЫМ
   * исполнением действия сверяется заново: разошёлся (запись изменена любым будущим путём/правкой
   * стора) → действие НЕ исполняется, честное уведомление «поручение изменилось после одобрения —
   * нужно новое подтверждение». Одобрение привязано к содержимому, а не к факту «когда-то одобряли».
   * ⚠️ predicate в отпечаток НЕ входит СОЗНАТЕЛЬНО: его tabId/url легитимно патчится self-heal'ом
   * вкладки (2026-07-25), а владельцу на confirm показывались именно condition+action.
   * Нет у легаси-записей (одобрены до волны F) — они исполняются как раньше (grandfather).
   */
  actionFingerprint?: string;
  /** Сработало с action, но живой агентской сессии не было → выполнить при следующем подключении. */
  pendingAction?: string;
  /** Когда действие отложили (для TTL: протухшее side-effect-поручение не исполняется молча). */
  pendingActionAt?: number;
  /**
   * Условие сейчас УДЕРЖИВАЕТСЯ met (durable). Edge-триггер действия (адверс-ревью 2026-07-28 [1]):
   * continuous + LLM-чекер генерит ДРЕЙФУЮЩИЙ summary (значение в тексте меняется каждый тик) →
   * антидребезг по строке промахивался и action исполнялся ПОВТОРНО каждые ~5 мин («второе сообщение
   * Кате»). Действие привязано к ПЕРЕХОДУ not-met → met, не к тексту summary.
   */
  metStreak?: boolean;
  /** Когда действие последний раз запускалось (durable) — диагностика «когда Джарвис это сделал». */
  lastActionAt?: number;
  /** Dead-watch (D3, форензика 2026-07-14): подряд провалившихся проверок. ≥порога → suspended + ОДНО
   *  честное уведомление владельцу (раньше 142 провала подряд горели в тишине). Сбрасывается на успехе. */
  consecutiveFailures?: number;
  /**
   * 🔴 Когда проверка последний раз реально ПРОШЛА (met или нет — важно, что источник ответил).
   * Живой дефект: ТРАНЗИЕНТНАЯ ошибка (Chrome закрыт на ночь, нет живой сессии) логировалась и
   * выходила — `consecutiveFailures` не рос, dead-watch не наступал, владельцу не говорили НИЧЕГО.
   * Утром он был уверен, что за заказом следят, а наблюдение 12 часов было слепым. Транзиентность
   * по-прежнему не копится к suspend (клиент вернётся), но МОЛЧАТЬ о слепоте нельзя.
   * Нет поля (легаси-запись) → отсчёт от createdAt (см. lastOkSince).
   */
  lastOkAt?: number;
  /** Когда владельцу УЖЕ сказали «не могу наблюдать» — чтобы сказать ОДИН раз, а не каждый тик.
   *  Снимается первой же удачной проверкой (восстановились → следующая слепота снова заслуживает слова). */
  blindNotifiedAt?: number;
}

/** Итог одной проверки наблюдения. Чистая структура (checker её возвращает). */
export interface CheckResult {
  /** Выполнено ли условие ПРЯМО СЕЙЧАС. */
  met: boolean;
  /** Наблюдённое значение (для контекста/лога/дельты), напр. «61 200 USD». */
  value?: string;
  /** Фраза пользователю при срабатывании И строка для лога (по делу, без боллерплейта). */
  summary: string;
  /** Проверка не удалась (сеть/нет данных) — НЕ считаем met, логируем и пробуем в следующий тик. */
  error?: string;
  /** Ревью р2 #6: ошибка ТРАНЗИЕНТНАЯ (нет живой сессии клиента) — НЕ инкрементит dead-watch (клиент
   *  вернётся). Отличаем от неисполнимого условия (реальный провал, копится к suspend). */
  transient?: boolean;
}

/** Проверяльщик условия наблюдения. Инъектируется (LLM+web/market в server.ts; мок в тестах). */
export type WatchChecker = (w: Watch) => Promise<CheckResult>;

/** Нижний порог «наблюдение ослепло» — сколько ждём удачной проверки, прежде чем честно сказать. */
export const BLIND_MIN_MS = 6 * 3600_000;

/**
 * Порог слепоты: max(6ч, 20×интервал). Почему не просто 6ч — у редкого наблюдения (раз в сутки) шесть
 * часов это ОДИН пропущенный тик, паниковать рано; почему не просто 20 интервалов — у частого (5с)
 * это полторы минуты, и любой перезапуск клиента будил бы владельца.
 */
export function blindThresholdMs(w: Pick<Watch, "intervalMs">): number {
  return Math.max(BLIND_MIN_MS, 20 * w.intervalMs);
}

/** С какого момента у наблюдения не было НИ ОДНОЙ удачной проверки (легаси/новая запись — от постановки). */
export function lastOkSince(w: Pick<Watch, "lastOkAt" | "createdAt">): number {
  return w.lastOkAt ?? w.createdAt;
}

/** Наблюдение ослепло: удачной проверки не было дольше порога (см. blindThresholdMs). */
export function isBlind(w: Pick<Watch, "intervalMs" | "lastOkAt" | "createdAt">, now: number): boolean {
  return now - lastOkSince(w) >= blindThresholdMs(w);
}

/** Время следующей проверки наблюдения: ещё не проверяли → сейчас (сразу базовый замер), иначе +интервал. */
export function dueAt(w: Watch, now: number): number {
  return w.lastCheckAt === undefined ? now : w.lastCheckAt + w.intervalMs;
}

/**
 * F4 (волна F): отпечаток одобренной операции наблюдения-с-действием. РОВНО то, что владелец видел на
 * confirm («когда „condition" — выполнить „action"», в контексте what) ПЛЮС предикат — для
 * predicate-триггерных наблюдений именно он и есть фактическое условие запуска действия (контроль
 * волны F: без него подмена `predicate.value/op` меняла УСЛОВИЕ запуска, не трогая отпечаток).
 *
 * Из предиката исключены АДРЕСНЫЕ поля `tabId`/`url`: их легитимно патчит self-heal вкладки
 * (2026-07-25) после ремонта выгруженной/закрытой вкладки — включи мы их, здоровое наблюдение
 * получило бы ложное «поручение изменилось» и было бы приостановлено.
 * Чистая функция — сверка при создании и перед исполнением обязана давать одинаковый результат
 * на неизменённой записи.
 */
export function watchActionFingerprint(w: Pick<Watch, "what" | "condition" | "action" | "predicate">): string {
  const basis = JSON.stringify([w.what, w.condition, w.action ?? "", stablePredicate(w.predicate)]);
  return createHash("sha256").update(basis, "utf8").digest("hex").slice(0, 32);
}

/**
 * ПРЕДЫДУЩАЯ схема отпечатка (what|condition|action, БЕЗ предиката) — записи, созданные между
 * первым коммитом волны F и его контролем, несут именно её. Сверять их текущей схемой значило бы
 * массово суспендить ЗДОРОВЫЕ наблюдения с ложным «поручение изменилось после одобрения» (мой же
 * фикс как источник дефекта — типовая ловушка проекта). Совпадение по легаси-схеме доказывает
 * неизменность ровно того, что тогда и одобрялось, — этого достаточно.
 */
export function watchActionFingerprintLegacy(w: Pick<Watch, "what" | "condition" | "action">): string {
  const basis = JSON.stringify([w.what, w.condition, w.action ?? ""]);
  return createHash("sha256").update(basis, "utf8").digest("hex").slice(0, 32);
}

/** Предикат для отпечатка: стабильный порядок ключей, без адресных tabId/url (их правит self-heal). */
function stablePredicate(p: unknown): unknown {
  if (p === undefined || p === null) return null;
  if (Array.isArray(p)) return p.map(stablePredicate);
  if (typeof p === "object") {
    const src = p as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(src).sort()) {
      if (k === "tabId" || k === "url") continue;
      out[k] = stablePredicate(src[k]);
    }
    return out;
  }
  return p;
}

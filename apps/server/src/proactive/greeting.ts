/**
 * Контекстное приветствие сессии (§9/§11) — «живое присутствие».
 *
 * Вместо канонной строки: учитываем ВРЕМЯ СУТОК и ПАМЯТЬ (имя, факты, недавние темы) →
 * короткий живой опенер, при уместности с проактивным вопросом. Это и есть «помнит контекст
 * между сессиями». Best-effort: нет имени/ключа/таймаут → детерминированный фолбэк (мгновенно).
 */
import { type Tier, createLogger } from "@jarvis/shared";
import type { ILlmProvider } from "../integrations/llm.js";
import type { EpisodicMemory } from "../memory/episodic.js";

const log = createLogger("proactive:greeting");

export interface GreetingDeps {
  llm: ILlmProvider;
  episodic: EpisodicMemory;
  models: Record<Exclude<Tier, "tier0">, string>;
}

/** Что Джарвис знает о пользователе (инъекция из профиля — без глобального состояния). */
export interface GreetingWho {
  name?: string;
  facts?: readonly string[];
}

/** Часть суток для приветствия (по локальному времени сервера). */
export function timeOfDay(d: Date = new Date()): string {
  const h = d.getHours();
  if (h < 5) return "Доброй ночи";
  if (h < 12) return "Доброе утро";
  if (h < 18) return "Добрый день";
  return "Добрый вечер";
}

/**
 * Заявление о ДЕЙСТВИИ или о ПРОВЕРЕННОМ СОСТОЯНИИ в приветствии (ревью 2026-09-24, T-F10).
 *
 * Опенер строится БЕЗ инструментов: модель ничего не проверяла, не смотрела почту, не знает, «всё ли в
 * норме». А дворецкий жанр тянет её сказать «я проверил — всё спокойно» — это ложный отчёт о работе,
 * которой не было (закон честности исхода). Промпт это запрещает, но гарантия — только код: такая фраза
 * отбрасывается и звучит детерминированный опенер. Ошибиться в сторону фолбэка дёшево (теряется лишь
 * «живость»), пропустить выдумку — дорого, поэтому сеть широкая. Границы слова — `\p{L}`, не `\b`
 * (на кириллице `\b` не работает).
 */
const ACTION_CLAIM_PARTS: readonly string[] = [
  // первое лицо прошедшего времени: «проверил(а)», «посмотрел», «заглянул», «нашёл», «подготовил»…
  "(?:пере|по)?провер(?:ил|ила|или)(?:сь)?",
  "(?:по|про|пере)?смотрел[аи]?",
  "(?:за|по)глянул[аи]?",
  "узнал[аи]?",
  "выяснил[аи]?",
  "уточнил[аи]?",
  "сверил[аи]?",
  "изучил[аи]?",
  "обнаружил[аи]?",
  "заметил[аи]?",
  "наш[её]л|нашла",
  "прочитал[аи]?|прочёл|прочел",
  "подготовил[аи]?|собрал[аи]?|обновил[аи]?|настроил[аи]?|отследил[аи]?|просканировал[аи]?",
  // настоящее время восприятия: на старте он ничего не видит и не слышит
  "вижу|слышу",
  // заявления о состоянии, которое нужно было ПРОВЕРИТЬ: «все системы в норме», «всё спокойно»
  // (String.raw — чтобы `\s`/`\d`/`\p{L}` дошли до RegExp, а не съелись строковым литералом)
  String.raw`систем[аы]?\s+(?:в\s+норме|в\s+порядке|работа[юе]т)`,
  String.raw`вс[её]\s+(?:в\s+порядке|в\s+норме|спокойно|тихо|штатно)`,
  String.raw`(?:новых|непрочитанных)\s+(?:писем|сообщений|уведомлений)`,
  String.raw`(?:писем|сообщений|уведомлений)\s+(?:нет|не\s+было)|нет\s+(?:новых\s+)?(?:писем|сообщений|уведомлений)`,
  String.raw`\d+\s+(?:новых|непрочитанн\p{L}*|писем|сообщени\p{L}*|письм\p{L}*)`,
];
const ACTION_CLAIM_RE = new RegExp(String.raw`(?<!\p{L})(?:${ACTION_CLAIM_PARTS.join("|")})(?!\p{L})`, "iu");

/** Утверждает ли опенер действие/проверку, которых не было. ЧИСТАЯ функция (T-F10). */
export function claimsUnperformedAction(text: string): boolean {
  return ACTION_CLAIM_RE.test(text);
}

/** Промис под мягким таймаутом: контекст приветствия НЕОБЯЗАТЕЛЕН, не задерживаем онбординг. */
function raceTimeout<T>(p: Promise<T>, ms: number): Promise<T> {
  return Promise.race([
    p,
    new Promise<T>((_, reject) => {
      const t = setTimeout(() => reject(new Error("timeout")), ms);
      if (typeof t === "object" && "unref" in t) (t as { unref?: () => void }).unref?.();
    }),
  ]);
}

/**
 * Собрать приветствие. Без имени — онбординг (спрашиваем обращение), без LLM. Иначе, если есть
 * живой мозг — короткий контекстный опенер (haiku) с учётом времени, фактов и недавней памяти;
 * любой сбой/таймаут → детерминированный фолбэк по времени суток и имени.
 */
export async function buildGreeting(deps: GreetingDeps, userId: string, who: GreetingWho): Promise<string> {
  const name = who.name;
  const tod = timeOfDay();
  // Обращение дворецкого — «сэр», НЕ по имени (имя знаем для узнавания, не для оклика). Онбординг без имени.
  const fallback = name
    ? `${tod}, сэр. Джарвис к вашим услугам.`
    : `${tod}. Джарвис к вашим услугам. Как мне к вам обращаться?`;
  if (!name || !deps.llm.live) return fallback;

  try {
    const facts = (who.facts ?? []).slice(0, 8);
    // НЕ тянем сюда «недавние эпизоды» векторным поиском: это вытаскивало случайный/мусорный
    // контекст (авто-залогированные реплики, мисс-транскрипты) и Джарвис «вспоминал» на старте
    // то, чего пользователь не говорил. На старте — чисто. Проактивный повод — ТОЛЬКО из
    // курируемых фактов профиля (образ жизни, который Джарвис осознанно сохранил), не из сырых событий.
    const sys =
      "Ты — Джарвис, лаконичный голосовой дворецкий. Поздоровайся ОДНОЙ короткой живой фразой " +
      "(до 14 слов), по-русски, на «вы», с учётом времени суток. Обращение — «сэр» либо без обращения; " +
      "по ИМЕНИ хозяина НЕ называй (это рушит образ дворецкого). Если среди известных фактов есть " +
      "что-то уместное к этому времени — можешь ненавязчиво это учесть. НИЧЕГО не выдумывай и не " +
      "«вспоминай» того, чего нет в фактах. Ты НИЧЕГО не проверял и не делал — инструментов у тебя сейчас нет: " +
      "не говори «проверил/посмотрел/вижу/всё в порядке/писем нет». Без markdown, без воды, без перечислений.";
    const ctx =
      `Время суток: ${tod}.` +
      (facts.length ? ` Известные факты о пользователе: ${facts.join("; ")}.` : "");
    const resp = await raceTimeout(
      deps.llm.complete({
        tier: "haiku",
        model: deps.models.haiku,
        systemStatic: sys,
        messages: [{ role: "user", content: ctx }],
      }),
      2800,
    );
    const line = resp.text.trim();
    if (!line) return fallback;
    // T-F10: опенер «я проверил…/всё спокойно» — выдумка (проверок не было) → честный детерминированный опенер.
    if (claimsUnperformedAction(line)) {
      log.info("приветствие модели отброшено: заявляет действие/проверку, которых не было", { line: line.slice(0, 80) });
      return fallback;
    }
    return line;
  } catch {
    return fallback;
  }
}

/**
 * САМООСМОТР: Джарвис сам замечает, что у него ломается (волна I, 2026-08-31).
 *
 * Инструменты самоулучшения (`self_weaknesses` / `self_code_*` / `self_patch`) отвечают на ВОПРОС
 * владельца. Но владелец не обязан догадываться, что стоит спросить: повторяющийся отказ виден в
 * durable-логах, а не в разговоре. Здесь — редкая проактивная реплика «вот что у меня повторяется,
 * могу разобраться», собранная ЧИСТО из уже посчитанных слабостей, без LLM и без выдумок.
 *
 * Правила те же, что у брифинга и доклада об инцидентах (уроки волны D):
 *  • нечего сказать — МОЛЧИМ (никаких «у меня всё отлично»);
 *  • редко: раз в несколько дней, по календарному гейту, а не на каждый коннект;
 *  • канал доставки — retriable: пока реплика не прозвучала, гейт НЕ сдвигается;
 *  • это ПРЕДЛОЖЕНИЕ, а не отчёт о работе: чинить или нет — решает владелец.
 */
import type { Weakness } from "../self/weaknesses.js";

/** Слабость должна ПОВТОРЯТЬСЯ заметно, иначе это шум, а не повод беспокоить владельца. */
const MIN_COUNT = 3;
/** Голос — узкий канал: называем максимум две вещи, остальное «и ещё N». */
const MAX_ITEMS = 2;

export interface SelfReviewGate {
  /** Когда докладывали в прошлый раз (unix ms), undefined — никогда. */
  lastReviewedAt?: number;
  /** Раз во сколько дней вообще заводим этот разговор. */
  everyDays: number;
  /** Разговорный ход владельца идёт прямо сейчас? (в dev-сессии и при killswitch — не зовём вовсе) */
  enabled: boolean;
}

/** Пора ли осматривать себя. Чистая функция — время инъектируется. */
export function shouldSelfReview(gate: SelfReviewGate, now: number): boolean {
  if (!gate.enabled) return false;
  const everyMs = Math.max(1, gate.everyDays) * 24 * 60 * 60 * 1000;
  if (!gate.lastReviewedAt) return true;
  return now - gate.lastReviewedAt >= everyMs;
}

/**
 * Реплика самоосмотра или null (молчим). Формулировка — НАМЕРЕНИЕ разобраться, не обещание починки:
 * обещать «исправлю» до того, как правка прошла тесты и владелец её принял, значит заявлять результат,
 * которого нет (закон честности; ровно та же грань, что у «Готово» без сверки).
 */
export function buildSelfReview(weaknesses: readonly Weakness[]): string | null {
  const notable = weaknesses.filter((w) => w.count >= MIN_COUNT);
  if (notable.length === 0) return null;
  const head = notable.slice(0, MAX_ITEMS).map((w) => w.title).join("; ");
  const rest = notable.length > MAX_ITEMS ? ` И ещё ${notable.length - MAX_ITEMS} по мелочи.` : "";
  return (
    `Сэр, посмотрел на свои логи. Повторяется вот что: ${head}.${rest} ` +
    `Могу разобраться в своём коде и починить — скажите «почини себя», и займусь.`
  );
}

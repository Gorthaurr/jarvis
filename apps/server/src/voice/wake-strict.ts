/**
 * СТРОГОЕ обращение и «только обращение» для подстраховки промаха KWS (ревью 28.09). Общий wake-путь опирается ещё и на
 * акустический детектор клиента; у подстраховки его нет — решает только текст, поэтому он строже общего `wake.ts`.
 */
import { COURTESY_TAIL, NOISE_WORDS, PREFIX_FUNCTION_WORDS, TOKEN_RE, stripWakeDetailed } from "./wake.js";

/**
 * Строгое обращение (ревью 28.09, B3): явный вариант имени (без fuzzy и склонений: «Джарвису»,
 * «Гаррис», «jars» — нет) в ПЕРВЫХ двух токенах («Эй, Джарвис, …», «Джарвис, …»). Обычный wake-путь опирается ещё и на
 * акустический детектор клиента; у подстраховки его нет — решает только текст, поэтому он строже: «я вчера сказал Джарвису
 * открыть ютуб» и «мой Джарвис опять глючит» не будят.
 */
export function isWakeAddressedStrict(text: string): boolean {
  const tokens = (text.match(TOKEN_RE) ?? []).map((t) => t.toLowerCase());
  const at = tokens.slice(0, 3).findIndex((t) => STRICT_WAKE_RE.test(t));
  // Перед именем — только служебные слова («Э-э», «Ну вот», «Эй», «Слушай»): «Железный человек: Джарвис, …» (фильм) — нет.
  return at >= 0 && tokens.slice(0, at).every((t) => PREFIX_FUNCTION_WORDS.has(t) || COURTESY_TAIL.has(t) || NOISE_WORDS.has(t));
}

/**
 * Узкий список для подстраховки: только формы имени («Джарвис», «Жарвис», «Джервис», «Жорвит»…) и «дж→г» Deepgram
 * («Гарвис»). НЕ входят фамилии/омонимы из общего CORE («Гаррис», «Jarry», «Ярвис», «Джарис», «Jares») — без акустики
 * клиента они давали ложные ходы (ревью 28.09, #5).
 */
const STRICT_WAKE_RE = new RegExp(
  "(?<![\\p{L}])(?:джарвис|джарвес|джарвиз|джарвиц|джарвиш|джарвич|джервис|жарвис|жарвес|жарвиз|жарвиц|жорвис|жорвит|жорвес|джорвис|гарвис|гарвес|гарвиз|гарвиц|гарвиш|jarvis|jarves|jarvees|jervis)(?![\\p{L}])",
  "iu",
);

/**
 * Во фразе ТОЛЬКО обращение: до/после него лишь служебные слова, междометия, вежливость («Эй, Джарвис.», «Слушай,
 * Джарвис», «Привет, Джарвис»). Такая подстраховка не запускает ход на обрывке — владелец договаривает (#6).
 */
export function isBareWake(text: string): boolean {
  const { command } = stripWakeDetailed(text);
  const words = command.toLowerCase().match(TOKEN_RE) ?? [];
  return words.every((w) => PREFIX_FUNCTION_WORDS.has(w) || COURTESY_TAIL.has(w) || NOISE_WORDS.has(w));
}


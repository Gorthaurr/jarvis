/**
 * Кого из очереди озвучки произносим следующим (вынесено из pipeline.ts: аудит прод-логов 27.09, A3).
 *
 * Срочное (напоминания-будильники) — строго по очереди, FIFO, и всегда, даже когда владелец занят.
 * 🔴 Для НЕсрочных порядок обратный — СВЕЖИЙ ВПЕРЁД (лог 2026-09-02: шторм из шести задач, девять реплик
 * потеряно за десять минут). FIFO сначала произносит самый СТАРЫЙ итог, и пока он звучит, свежие протухают
 * по TTL — владелец слышит ответ на вопрос, о котором забыл, и НЕ слышит ответ на тот, что задал только что.
 *
 * §9 «не мешать»: владелец занят (звонок/полный экран/блокировка) → несрочный ПРОАКТИВ держим до освобождения.
 * Но ответ на ЕГО СОБСТВЕННЫЙ вопрос (origin user-turn: спасённая реплика отменённого хода, итог его задачи)
 * — не проактив: он только что говорил с Джарвисом и ждёт именно этот ответ. A3 (24.09 18:37): спасённый
 * ответ шёл как проактив, busy-гейт держал его до TTL, и реплика пропала молча.
 */
import type { SpeechOrigin } from "./pipeline.js";

export interface PickableSpeech {
  urgent: boolean;
  /** Когда поставлена в очередь (мс). */
  at: number;
  origin?: SpeechOrigin;
}

/** Индекс следующей реплики; −1 — отдавать сейчас нечего (занят, а срочного и ответов владельцу нет). */
export function pickNextSpeech(queue: readonly PickableSpeech[], busy: boolean): number {
  const urgent = queue.findIndex((p) => p.urgent);
  if (urgent >= 0) return urgent;
  let best = -1;
  for (let i = 0; i < queue.length; i++) {
    if (busy && queue[i]!.origin !== "user-turn") continue;
    if (best < 0 || queue[i]!.at > queue[best]!.at) best = i;
  }
  return best;
}

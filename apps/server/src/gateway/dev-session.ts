/**
 * Признак DEV-сессии (текст-драйвер `_jarvis_cmd.mjs`, смоук-скрипты, автотесты) по clientVersion.
 *
 * Зачем отдельная функция: этим гейтом закрыты ВСЕ одноразовые ресурсы владельца, и правило у них
 * одно — «прогон драйвера не должен потратить то, что предназначено человеку»:
 *   • приветствие-онбординг (кулдаун 6ч),
 *   • сон-цикл консолидации памяти (раз в календарный день),
 *   • ДОКЛАД О СБОЯХ (durable-маркер: съеденный доклад владелец не услышит НИКОГДА — контрольное
 *     ревью 2026-07-29 поймало ровно это: утренний смоук агента «съедал» ночной инцидент),
 *   • сводка дня, ambient-уведомления, недоставленные напоминания и наблюдения, отложенные поручения
 *     watch (их флаш ИСПОЛНЯЕТ поручение и durable-вычёркивает его из стора).
 * Раньше регэксп жил копипастой в трёх местах — расхождение означало бы тихую дыру в одном из них.
 *
 * ⚠️ КОНТРАКТ: клиент-НЕ-владелец обязан назвать себя так, чтобы попасть под этот шаблон. Все драйверы
 * репозитория (`_jarvis_cmd.mjs` → "cmd-test", `_qa_battery.mjs` → "qa", `_qa_slow.mjs` → "qa-slow")
 * учтены; добавляешь новый скрипт — либо назови его по шаблону, либо расширь список (контроль-6 волны D:
 * «qa» и «qa-slow» проходили как ЖИВОЙ владелец и съедали ровно то, что гейт защищает).
 */

/** Dev-сессия (драйвер/тест/смоук/QA), а не живой клиент владельца. Чистая функция. */
export function isDevSession(clientVersion?: string): boolean {
  return /cmd|test|driver|qa|smoke|probe|bench|script/i.test(clientVersion ?? "");
}

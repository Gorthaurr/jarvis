-- Волна H (шаг 2), 2026-08-31: SUPERSEDE вместо бинарного stale.
--
-- Проблема: `stale` выставляется ТОЛЬКО явной командой владельца («забудь, что…»), а факты, которые
-- просто устарели («работаю в Сбере» → «работаю в Яндексе»), остаются равноправными в памяти: их
-- косинус ~0.86 ниже дедуп-порога 0.93, поэтому пишутся оба. В доверенном блоке промпта это даёт
-- прямое нарушение честности — модель уверенно называет устаревшее.
--
-- Решение (по образцу bi-temporal памяти: факт не удаляют, а помечают невалидным с момента X):
--   • invalid_at    — КОГДА факт перестал быть верным (null = действует);
--   • superseded_by — КАКАЯ запись его заменила (для витрины «было → стало» во вкладке «Память»).
-- Отдельно от `stale`: stale — решение ВЛАДЕЛЬЦА («забудь»), invalid_at — вывод СИСТЕМЫ («устарело»).
-- Схлопывать их нельзя: владелец должен видеть, кто именно убрал факт (иначе молчаливое исчезновение).
ALTER TABLE episodic_memory ADD COLUMN IF NOT EXISTS invalid_at TIMESTAMPTZ NULL;
ALTER TABLE episodic_memory ADD COLUMN IF NOT EXISTS superseded_by UUID NULL;

-- Поиск/листинг фильтруют по invalid_at IS NULL — индекс держит горячий путь дешёвым.
CREATE INDEX IF NOT EXISTS idx_episodic_valid ON episodic_memory (user_id, created_at DESC) WHERE stale = FALSE AND invalid_at IS NULL;
